import express from "express";
import { homePage } from "../controllers/homeController.js";
import {loginPage,registerPage,forgotPasswordPage,dashboardPage,loginUser,registerUser,logoutUser} from "../controllers/authController.js";
import { bookController } from "../controllers/BookController.js";
const router=express.Router();
router.get("/",homePage);
router.get("/login",loginPage);
router.post("/login",loginUser);
router.get("/register",registerPage);
router.post("/register",registerUser);
router.get("/forgot-password",forgotPasswordPage);
router.get("/dashboard",dashboardPage);
router.get("/logout",logoutUser);
router.get("/books",bookController.index);
router.post("/books",bookController.insert);
router.get("/books/:id",bookController.show);
router.post("/books/:id",bookController.update);
router.post("/books/:id/delete",bookController.delete);
router.post("/books/:id/borrow",bookController.borrow);
router.post("/books/:id/return",bookController.returnBook);
export default router;
